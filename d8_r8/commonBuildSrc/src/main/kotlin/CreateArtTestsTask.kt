import org.gradle.api.tasks.TaskAction

@CacheableTask
public abstract class CreateArtTestsTask : DefaultTask() {
  @get:[InputFiles PathSensitive(PathSensitivity.RELATIVE)]
  public abstract val artTestCaseDirectory: DirectoryProperty

  @get:OutputDirectory public abstract val outputDir: DirectoryProperty

  @TaskAction
  public fun createTests() {
    val outputDirectory = outputDir.get().asFile
    outputDirectory.deleteRecursively()
    val artTestCaseSubdirectory = File(artTestCaseDirectory.get().asFile, "dx")
    check(artTestCaseSubdirectory.exists())
    val subDirectories = artTestCaseSubdirectory.toPath().listDirectoryEntries()
    val testCases = subDirectories.map { it.fileName.toString() }
    for ((tool, toolEnum) in
      listOf("r8" to "R8", "d8" to "R8_AFTER_D8", "r8cf" to "D8_AFTER_R8CF")) {
      val packageDirectory = File(outputDirectory, "com/android/tools/r8/art/none/$tool")
      packageDirectory.mkdirs()
      for (testCase in testCases) {
        val className = "Art${testCase.replace("-", "_")}Test"
        val testRuntimes =
          if (testCase == "800-smali")
            "withDexRuntimesEndingAtExcluding(\n          com.android.tools.r8.ToolHelper.DexVm.Version.V17_0_0)"
          else "withDexRuntimes()"
        File(packageDirectory, "$className.java")
          .writeText(
            """// Copyright (c) 2016, the R8 project authors. Please see the AUTHORS file
// for details. All rights reserved. Use of this source code is governed by a
// BSD-style license that can be found in the LICENSE file.
package com.android.tools.r8.art.none.$tool;

import static com.android.tools.r8.R8RunArtTestsTest.DexTool.NONE;

import com.android.tools.r8.R8RunArtTestsTest;
